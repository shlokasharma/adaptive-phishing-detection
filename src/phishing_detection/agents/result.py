"""
Standardized result schema for Phase 3 phishing detection agents.

The AgentResult object provides a common output contract for all
specialized agents.

An agent may internally use machine learning, rules, external
intelligence, transformers, LLMs, or other analysis mechanisms.
Regardless of implementation, the result exposed to the orchestrator
must follow this schema.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any

from phishing_detection.agents.evidence import Evidence
from phishing_detection.agents.base import AgentExecutionMetadata


VALID_LABELS = {0, 1}

VALID_LABEL_NAMES = {
    "legitimate",
    "phishing",
}


@dataclass
class AgentResult:
    """
    Standardized output produced by a phishing detection agent.

    Parameters
    ----------
    agent_name:
        Unique name of the agent that generated the result.

    modality:
        Modality analyzed by the agent.

    label:
        Binary prediction:

            0 = legitimate
            1 = phishing

    label_name:
        Human-readable prediction label.

    phishing_probability:
        Estimated probability that the analyzed input is phishing.

    confidence:
        Confidence associated with the prediction.

    uncertainty:
        Uncertainty associated with the prediction.

    evidence:
        Structured evidence generated by the agent.

    execution_metadata:
        Information about execution time, model used, and other
        execution-level information.

    metadata:
        Additional agent-specific information.
    """

    agent_name: str
    modality: str
    label: int
    label_name: str
    phishing_probability: float
    confidence: float
    uncertainty: float
    evidence: list[Evidence] = field(default_factory=list)
    execution_metadata: AgentExecutionMetadata | None = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        self._validate()

    def _validate(self) -> None:
        """Validate the standardized agent result."""

        if not self.agent_name.strip():
            raise ValueError(
                "agent_name must not be empty."
            )

        if not self.modality.strip():
            raise ValueError(
                "modality must not be empty."
            )

        if self.label not in VALID_LABELS:
            raise ValueError(
                f"Invalid label: {self.label}. "
                "Expected 0 (legitimate) or 1 (phishing)."
            )

        expected_label_name = (
            "phishing"
            if self.label == 1
            else "legitimate"
        )

        if self.label_name != expected_label_name:
            raise ValueError(
                "label_name does not match label. "
                f"Expected {expected_label_name!r}."
            )

        self._validate_probability(
            self.phishing_probability,
            "phishing_probability",
        )

        self._validate_probability(
            self.confidence,
            "confidence",
        )

        self._validate_probability(
            self.uncertainty,
            "uncertainty",
        )

        if not isinstance(self.evidence, list):
            raise TypeError(
                "evidence must be a list of Evidence objects."
            )

        if not all(
            isinstance(item, Evidence)
            for item in self.evidence
        ):
            raise TypeError(
                "Every item in evidence must be an Evidence object."
            )

        if self.execution_metadata is not None and not isinstance(
            self.execution_metadata,
            AgentExecutionMetadata,
        ):
            raise TypeError(
                "execution_metadata must be an "
                "AgentExecutionMetadata object or None."
            )

        if not isinstance(self.metadata, dict):
            raise TypeError(
                "metadata must be a dictionary."
            )

    @staticmethod
    def _validate_probability(
        value: float,
        field_name: str,
    ) -> None:
        """Validate a probability-like value."""

        if not isinstance(value, (int, float)):
            raise TypeError(
                f"{field_name} must be a number."
            )

        if not 0.0 <= float(value) <= 1.0:
            raise ValueError(
                f"{field_name} must be between 0 and 1."
            )

    def to_dict(self) -> dict[str, Any]:
        """
        Convert the result into a serializable dictionary.

        Nested dataclasses such as Evidence and
        AgentExecutionMetadata are converted automatically.
        """
        return asdict(self)

    @property
    def is_phishing(self) -> bool:
        """Return True when the result predicts phishing."""
        return self.label == 1

    @property
    def is_legitimate(self) -> bool:
        """Return True when the result predicts legitimate."""
        return self.label == 0

    @property
    def evidence_count(self) -> int:
        """Return the number of evidence items."""
        return len(self.evidence)

    @classmethod
    def from_probability(
        cls,
        *,
        agent_name: str,
        modality: str,
        phishing_probability: float,
        evidence: list[Evidence] | None = None,
        confidence: float | None = None,
        execution_metadata: AgentExecutionMetadata | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> "AgentResult":
        """
        Construct an AgentResult directly from a phishing probability.

        The predicted label is determined using a 0.5 decision threshold.

        If confidence is not explicitly supplied, confidence is defined
        as the probability of the predicted class.
        """

        if not 0.0 <= float(phishing_probability) <= 1.0:
            raise ValueError(
                "phishing_probability must be between 0 and 1."
            )

        phishing_probability = float(phishing_probability)

        label = int(phishing_probability >= 0.5)

        label_name = (
            "phishing"
            if label == 1
            else "legitimate"
        )

        if confidence is None:
            confidence = (
                phishing_probability
                if label == 1
                else 1.0 - phishing_probability
            )

        uncertainty = round(1.0 - float(confidence), 10)

        return cls(
            agent_name=agent_name,
            modality=modality,
            label=label,
            label_name=label_name,
            phishing_probability=phishing_probability,
            confidence=float(confidence),
            uncertainty=uncertainty,
            evidence=evidence or [],
            execution_metadata=execution_metadata,
            metadata=metadata or {},
        )